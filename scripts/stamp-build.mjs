#!/usr/bin/env node
// Writes build metadata (version, build number, commit, date) into the library
// and the demo. CI sets GITHUB_RUN_NUMBER / GITHUB_SHA; local builds get "dev".
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "packages/factfinch/package.json"), "utf8"));

function gitSha() {
  if (process.env.GITHUB_SHA) return process.env.GITHUB_SHA;
  try {
    return execSync("git rev-parse HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return "unknown";
  }
}

const info = {
  version: pkg.version,
  build: process.env.FACTFINCH_BUILD_NUMBER ?? process.env.GITHUB_RUN_NUMBER ?? "dev",
  commit: gitSha().slice(0, 12),
  builtAt: process.env.SOURCE_DATE_EPOCH
    ? new Date(Number(process.env.SOURCE_DATE_EPOCH) * 1000).toISOString()
    : new Date().toISOString(),
};

writeFileSync(
  join(root, "packages/factfinch/src/build-info.ts"),
  `// Generated by scripts/stamp-build.mjs. Do not edit.\n` +
    `export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`,
);
writeFileSync(join(root, "apps/demo/src/build-info.json"), JSON.stringify(info, null, 2) + "\n");
console.log(`stamped factfinch ${info.version}+build.${info.build} (${info.commit})`);
